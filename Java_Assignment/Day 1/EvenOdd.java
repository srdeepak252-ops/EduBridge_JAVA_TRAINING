//  Day 1   5th Question   Even or Odd

public class EvenOdd {
    public static void main(String[] args) {
         int num = 24;
        if (num % 2 == 0) {
            System.out.println(num + " is Even");
        }
         else {
            System.out.println(num + " is Odd");
        }

        num = 37;
        if (num % 2 == 0) {
            System.out.println(num + " is Even");
        }
         else {
            System.out.println(num + " is Odd");
        }
    
    }
}
